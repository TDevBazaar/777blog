export const capitulosDisponibles: Record<string, number[]> = {};

for (const c of capitulos) {
  if (!capitulosDisponibles[c.libroSlug]) capitulosDisponibles[c.libroSlug] = [];
  capitulosDisponibles[c.libroSlug].push(c.capitulo);
}

export function getCapitulo(libroSlug: string, capitulo: number): Capitulo | undefined {
  return capitulos.find((c) => c.libroSlug === libroSlug && c.capitulo === capitulo);
}

export function getCapitulosDeLibro(libroSlug: string): Capitulo[] {
  return capitulos.filter((c) => c.libroSlug === libroSlug);
}
