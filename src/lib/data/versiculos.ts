export const temas = [...new Set(versiculos.map((v) => v.tema))].sort();

export function getVersiculoDelDia(fecha = new Date()): Versiculo {
  const inicio = new Date(fecha.getFullYear(), 0, 0);
  const dia = Math.floor((fecha.getTime() - inicio.getTime()) / 86400000);
  return versiculos[dia % versiculos.length];
}

export function formatFecha(fecha: Date): string {
  return new Intl.DateTimeFormat("es-ES", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(fecha);
}
